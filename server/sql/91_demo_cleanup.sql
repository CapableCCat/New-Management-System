-- 演示报名（139000008xx，T33）
DELETE FROM recruit_apply WHERE phone LIKE '139000008%';

-- 自测账号（139000002xx，T34）—— 超管 1 / 社长团 5 / 部长 8 / 部员 50
DELETE FROM user WHERE phone LIKE '139000002%';

